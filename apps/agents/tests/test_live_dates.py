import pytest

from cold_call_agents.live.dates import parse_date

CASES = [
    ("2024-05-03", "2024-05-03"),
    ("2024-05-03T10:00:00Z", "2024-05-03"),
    ("2024-05-03T10:00:00+02:00", "2024-05-03"),
    ("2024-05-03T10:00:00.123456", "2024-05-03"),
    ("Fri, 03 May 2024 10:00:00 GMT", "2024-05-03"),
    ("Fri, 03 May 2024 10:00:00 +0000", "2024-05-03"),
    ("2024-05", "2024-05-01"),
    ("2024", "2024-01-01"),
    ("May 3, 2024", "2024-05-03"),
    ("May 3rd, 2024", "2024-05-03"),
    ("3 May 2024", "2024-05-03"),
    ("Sept 3, 2024", "2024-09-03"),
    ("May 2024", "2024-05-01"),
    (1714730400, "2024-05-03"),
    (1714730400.5, "2024-05-03"),
    ("1714730400", "2024-05-03"),
    (1714730400000, "2024-05-03"),
    (None, None),
    ("", None),
    ("   ", None),
    ("not a date", None),
    ("2024-13", None),
    ("2024-02-30", None),
    ("Foo 3, 2024", None),
    ("yesterday", None),
    (True, None),
    (-5, None),
    (["2024-05-03"], None),
    ({"d": 1}, None),
    (10**30, None),
]


@pytest.mark.parametrize("value,expected", CASES)
def test_parse_date(value, expected):
    assert parse_date(value) == expected
